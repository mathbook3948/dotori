/// Strings of the onboarding window.
#[derive(Debug)]
pub(crate) struct Onboarding {
    pub(crate) key_step: &'static str,
    pub(crate) look_step: &'static str,
    pub(crate) elsewhere_step: &'static str,
    pub(crate) start: &'static str,
    pub(crate) next: &'static str,
    pub(crate) begin_chat: &'static str,
    pub(crate) back: &'static str,
    /// The greeting's first line, which names the assistant.
    pub(crate) hello: fn() -> String,
    pub(crate) ask_anything: &'static str,
    pub(crate) on_it: &'static str,
    pub(crate) schedule: &'static str,
    pub(crate) schedule_ask: &'static str,
    pub(crate) web: &'static str,
    pub(crate) web_ask: &'static str,
    pub(crate) pc: &'static str,
    pub(crate) pc_ask: &'static str,
    pub(crate) connect_title: &'static str,
    /// What the assistant does with the key, before the link that makes one.
    pub(crate) key_use: fn() -> String,
    pub(crate) make_key: &'static str,
    pub(crate) server_hint: &'static str,
    pub(crate) compatible: &'static str,
    pub(crate) address_label: &'static str,
    pub(crate) model_label: &'static str,
    pub(crate) key_label: &'static str,
    pub(crate) key_optional: &'static str,
    pub(crate) key_from_environment: &'static str,
    pub(crate) key_safe: &'static str,
    pub(crate) checking: &'static str,
    pub(crate) key_refused: &'static str,
    pub(crate) no_anthropic: &'static str,
    pub(crate) no_server: &'static str,
    pub(crate) look_title: &'static str,
    pub(crate) look_hint: &'static str,
    pub(crate) name_label: &'static str,
    pub(crate) theme_label: &'static str,
    pub(crate) elsewhere_title: &'static str,
    /// What turning a channel on does, which names the assistant.
    pub(crate) elsewhere_hint: fn() -> String,
    pub(crate) slack_app_token: &'static str,
    pub(crate) slack_bot_token: &'static str,
    pub(crate) slack_member: &'static str,
    pub(crate) bot_token: &'static str,
    pub(crate) user_id: &'static str,
    pub(crate) join_existing: &'static str,
    pub(crate) join_title: &'static str,
    pub(crate) join_hint: &'static str,
    pub(crate) code_label: &'static str,
    pub(crate) address_optional: &'static str,
    pub(crate) join: &'static str,
    pub(crate) joining: &'static str,
    pub(crate) code_unreadable: &'static str,
    pub(crate) address_needed: &'static str,
    pub(crate) join_failed: &'static str,
    /// What went wrong on this PC after the other one took the code, given the error.
    pub(crate) join_here_failed: fn(&str) -> String,
    /// The line after joining the PC of the given name, while its settings are on the way.
    pub(crate) joined: fn(&str) -> String,
    /// The line once the settings and keys came from the PC of the given name.
    pub(crate) received: fn(&str) -> String,
    pub(crate) receiving: &'static str,
    pub(crate) set_up_here: &'static str,
}

